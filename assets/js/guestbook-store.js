/* =====================================================================
   PHANTOM LOG · guestbook-store.js —— 留言的存取层（adapter）
   ---------------------------------------------------------------------
   页面只认 list() / add() 两个方法，所以后端可以随时换，页面代码不用动。
   现在默认 local：留言存在访客自己的浏览器里（只有他自己看得见）。
   接真后端时把 site.js 的 guestbook.store 改成 'remote' 并填 endpoint / key。

   —— 换成 Supabase 的完整步骤 ——
   1. 建项目，SQL Editor 里执行：
        create table guestbook (
          id        bigint generated by default as identity primary key,
          name      text not null check (char_length(name) between 1 and 20),
          text      text not null check (char_length(text) between 1 and 500),
          contact   text,                       -- 选填，见下面的列级权限
          page      text,
          at        timestamptz not null default now()
        );
        alter table guestbook enable row level security;
        -- 谁都能读（留言板本来就是公开的）
        create policy gb_read   on guestbook for select using (true);
        -- 谁都能写，但不能改别人的、也不能删
        create policy gb_insert on guestbook for insert with check (true);
        revoke update, delete on guestbook from anon, authenticated;
        -- 联系方式不让匿名读者读到（列级权限）：先收回整列，再单独放行其余列
        revoke select (contact) on guestbook from anon, authenticated;
        grant  select (id, name, text, page, at) on guestbook to anon;
   2. 把 Project URL 与 anon public key 填进 site.js 的 endpoint / key。
      注意：anon key 是公开的（就放在前端），所以**权限必须靠 RLS**，别用它当密码。
   ===================================================================== */
(function () {
  const S = window.PL_SITE || {};
  const C = S.guestbook || {};
  const KEY = 'pl-guestbook-v1';
  const LIMIT = 200;

  /* ---------- 本地：存在访客自己的浏览器里 ---------- */
  const local = {
    mode: 'local',
    async list() {
      try { return JSON.parse(localStorage.getItem(KEY) || '[]'); } catch (e) { return []; }
    },
    async add(msg) {
      const all = await this.list();
      const row = Object.assign({ id: 'l' + Date.now(), at: new Date().toISOString() }, msg);
      all.unshift(row);
      try { localStorage.setItem(KEY, JSON.stringify(all.slice(0, LIMIT))); } catch (e) { /* 隐私模式：本次有效 */ }
      return row;
    }
  };

  /* ---------- 远端：Supabase 的 REST 接口（没配好就不要切过来） ---------- */
  const remote = {
    mode: 'remote',
    _head(extra) {
      return Object.assign({
        apikey: C.key,
        Authorization: 'Bearer ' + C.key,
        'Content-Type': 'application/json'
      }, extra || {});
    },
    async list() {
      const t = C.table || 'guestbook';
      const r = await fetch(`${C.endpoint}/rest/v1/${t}?select=id,name,text,page,at&order=at.desc&limit=${LIMIT}`,
        { headers: this._head() });
      if (!r.ok) throw new Error('读取失败 ' + r.status);
      return r.json();
    },
    async add(msg) {
      const t = C.table || 'guestbook';
      const r = await fetch(`${C.endpoint}/rest/v1/${t}`, {
        method: 'POST',
        headers: this._head({ Prefer: 'return=representation' }),
        body: JSON.stringify(msg)
      });
      if (!r.ok) throw new Error('提交失败 ' + r.status);
      const rows = await r.json();
      return rows[0];
    }
  };

  const ready = C.store === 'remote' && C.endpoint && C.key;
  window.PL = window.PL || {};
  window.PL.gbStore = Object.assign({}, ready ? remote : local, {
    /* 联系方式在本地模式下根本不出浏览器；远端模式下靠列级权限挡住匿名读 */
    contactStaysLocal: !ready
  });
})();
